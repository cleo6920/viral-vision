def clean_file(filepath):
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            content = f.read()
    except UnicodeDecodeError:
        try:
            with open(filepath, 'r', encoding='latin-1') as f:
                content = f.read()
        except Exception as e:
            print(f"Error reading {filepath}: {e}")
            return

    new_content = content
    # Sort keys by length descending to avoid partial matching issues
    for mangled, fixed in sorted(replacements.items(), key=lambda x: len(x[0]), reverse=True):
        new_content = new_content.replace(mangled, fixed)
    
    for demo, generic in demo_fallbacks.items():
        new_content = new_content.replace(demo, generic)

    if new_content != content:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(new_content)
        print(f"Cleaned {filepath}")

